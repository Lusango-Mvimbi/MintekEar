/**
 * Insert any missing example managers and anonymous reviews.
 * Rows already stored are left as they are, including reviews people have posted
 * and reviews an administrator has hidden. Safe to run on every startup.
 */
export function ensureDemoSeed(db: DatabaseSync) {
  const now = Date.now();
  const today = reviewDate(now);
  const insertManager = db.prepare(
    "INSERT OR IGNORE INTO managers (id, name, title, division, sample, created_at) VALUES (?, ?, ?, ?, 1, ?)",
  );
  const insertReview = db.prepare(
    "INSERT OR IGNORE INTO reviews (id, manager_id, rating, body, created_at, hidden) VALUES (?, ?, ?, ?, ?, 0)",
  );
  const insertTag = db.prepare("INSERT OR IGNORE INTO review_tags (review_id, tag) VALUES (?, ?)");

  db.exec("BEGIN IMMEDIATE");
  try {
    for (const manager of managers) {
      insertManager.run(manager.id, manager.name, manager.title, manager.division, today);
    }
    for (const item of reviews) {
      insertReview.run(item.id, item.managerId, item.rating, item.body, reviewDate(now - item.ageMs));
      for (const tag of item.tags) insertTag.run(item.id, tag);
    }
    db.exec("COMMIT");
  } catch (error) {
    db.exec("ROLLBACK");
    throw error;
  }
}
